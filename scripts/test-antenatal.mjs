import assert from 'node:assert/strict';
import ts from 'typescript';
import { readFileSync } from 'node:fs';
const importTS = async file => {
 const source = readFileSync(new URL(file, import.meta.url), 'utf8');
 const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
 return import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
};
const { generateEnhancedConsult } = await importTS('../apps/Antenatal/services/geminiService.ts');
const template = 'GA: ***; steroids: ***; resuscitation: ***';
assert.equal(await generateEnhancedConsult(template, ''), template);
const draft=await generateEnhancedConsult(template, '24 weeks, PPROM');
assert.ok(draft.startsWith(template));
assert.ok(draft.includes('24 weeks, PPROM'));
assert.ok(!draft.includes('Complete (2 doses given)'));
assert.ok(!draft.includes('full active resuscitation'));
const structured = '**ANTENATAL CONSULTATION DRAFT**\nCare goal: pending';
assert.equal(await generateEnhancedConsult(template,structured),structured);
const { RISK_DATA } = await importTS('../apps/Antenatal/riskData.ts');
const { PARENT_COUNSELING_DATABASE } = await importTS('../apps/Antenatal/data/counselingData.ts');
const { VON_NETWORK_REPORT } = await importTS('../apps/Antenatal/data/vonNetworkReport.ts');
const { VON_HISTORICAL_GA } = await importTS('../apps/Antenatal/data/vonHistorical.ts');
const contextSource = readFileSync(new URL('../apps/Antenatal/utils/gestationContext.ts', import.meta.url), 'utf8')
 .replace(/import .* from .*;\r?\n/g, '');
const contextJS = ts.transpileModule(contextSource, {compilerOptions:{module:ts.ModuleKind.ES2022}}).outputText;
const contextModule = `const RISK_DATA=${JSON.stringify(RISK_DATA)};const PARENT_COUNSELING_DATABASE=${JSON.stringify(PARENT_COUNSELING_DATABASE)};const VON_NETWORK_REPORT=${JSON.stringify(VON_NETWORK_REPORT)};const VON_HISTORICAL_GA=${JSON.stringify(VON_HISTORICAL_GA)};\n${contextJS}`;
const { getGestationCounseling, syncGestationDraft, syncGestationReference, formatVONHistoricalReference } = await import(`data:text/javascript;base64,${Buffer.from(contextModule).toString('base64')}`);
assert.ok(formatVONHistoricalReference(23).includes('Derived survival: 47.1%'));
for (const ga of [24,25,26]) assert.ok(formatVONHistoricalReference(ga).includes('Derived survival: 77.4%'));
for (const ga of [27,28]) assert.ok(formatVONHistoricalReference(ga).includes('Derived survival: 92.3%'));
const { mergeCounselingDraft } = await importTS('../apps/Antenatal/utils/counselingDraft.ts');
const initialNote = mergeCounselingDraft('My editable template','Care goal: active');
const editedNote = initialNote.replace('Care goal: active','Care goal: active\nMy manual counseling addition')+'\nMy outside note';
const nextNote = mergeCounselingDraft(editedNote,'Care goal: palliative','Care goal: active');
assert.ok(nextNote.startsWith('--- LIVE COUNSELING DRAFT ---\nCare goal: palliative'));
assert.ok(nextNote.includes('My manual counseling addition'));
assert.ok(nextNote.includes('My outside note'));
assert.equal(nextNote.split('--- LIVE COUNSELING DRAFT ---').length,2);
const palliative = getGestationCounseling(23,'palliative');
assert.ok(!palliative.deliveryRoomPlan.includes('intubation'));
assert.ok(palliative.nicuExpectations.includes('not the selected care pathway'));
assert.ok(!getGestationCounseling(23,'active').deliveryRoomPlan.includes('If comfort care elected'));
assert.ok(getGestationCounseling(23,'pending').deliveryRoomPlan.includes('Care goal pending'));
for (let oldGA=22;oldGA<=28;oldGA++) for(let nextGA=22;nextGA<=28;nextGA++) {
 const before=getGestationCounseling(oldGA), after=getGestationCounseling(nextGA);
 assert.ok(after.diagnosticSummary.includes(`${nextGA} completed weeks`));
 assert.ok(after.longTermPrognosis.includes('not been independently verified'));
 assert.ok(after.longTermPrognosis.includes(`${RISK_DATA.prematurity.profiles[nextGA].stats[0].value}%`));
 const text=[before.diagnosticSummary,before.deliveryRoomPlan,before.nicuExpectations,before.longTermPrognosis,...before.faqs.map(f=>f.question+'\n'+f.answer),'Care goal: palliative; Parent: Alex; custom note: retain this.'].join('\n');
 const changed=syncGestationDraft(syncGestationReference(text,oldGA),oldGA,nextGA);
 assert.ok(changed.includes(after.diagnosticSummary));
 assert.ok(changed.includes(after.longTermPrognosis));
 assert.ok(changed.includes(after.faqs[0].question));
 assert.ok(changed.includes('Care goal: palliative; Parent: Alex; custom note: retain this.'));
 assert.equal(changed.split('--- CURRENT GESTATION REFERENCE (AUTO-UPDATED) ---').length,2);
 assert.equal(syncGestationReference(changed,nextGA),changed);
 const filled=syncGestationReference(`- Discussed current survival statistics for ${oldGA} weeks gestation in Canada (approx ***%).\n- Long-term neurodevelopmental risks discussed (Significant Disability approx ***%). Definitions of disability provided including motor, cognitive, and sensory.\nSteroids: ***`,oldGA);
 const moved=syncGestationDraft(filled,oldGA,nextGA);
 assert.ok(!moved.includes('approx ***%'));
 assert.ok(moved.includes(`${RISK_DATA.prematurity.profiles[nextGA].stats[0].value}% with active care`));
 assert.ok(moved.includes('Severe Intraventricular Hemorrhage: 8.1% (reported N=50,129)'));
 assert.ok(moved.includes('Cystic PVL: 2.7%'));
 assert.ok(moved.includes('Steroids: ***'));
}
assert.deepEqual(Object.keys(RISK_DATA.prematurity.profiles),['22','23','24','25','26','27','28']);
assert.deepEqual(Object.values(RISK_DATA.prematurity.profiles).map(p=>p.stats[0].value),[25,45,69,80,90,95,97]);
const { calculateCNNPrediction, formatCNNPostnatalNote } = await importTS('../apps/Antenatal/utils/cnnCalculatorModel.ts');
let cases=0;
for(const dayOfLife of [7,14,28]) for(let gestationalAge=22;gestationalAge<=29;gestationalAge++) for(const birthWeight of [250,675,1750]) for(const sex of ['male','female']) for(const respiratorySupport of ['ventilator','cpap','cannula','room_air']) {
 const input={dayOfLife,gestationalAge,birthWeight,sex,respiratorySupport};
 const result=calculateCNNPrediction(input);
 for(const key of ['survivalToDischarge','mortalityPriorToDischarge','mortalityOrMajorMorbidity','survivalWithoutMajorMorbidity','deathOrBPD','deathOrModSevereBPD','severeROP','pvl','lateNEC']) assert.ok(Number.isFinite(result[key]) && result[key]>=0 && result[key]<=100,key);
 assert.equal(result.survivalToDischarge+result.mortalityPriorToDischarge,100);
 assert.equal(result.survivalWithoutMajorMorbidity+result.mortalityOrMajorMorbidity,100);
 const note=formatCNNPostnatalNote(input,result);
 assert.ok(note.includes('not the official CNN NOPS model'));
 assert.ok(!note.includes('**Source:** Canadian Neonatal Network'));
 cases++;
}
console.log(`Antenatal reference and draft checks passed; ${cases} illustrative model cases checked. These are software checks, not clinical validation.`);
